-- v10.1: パスワード変更時のセッション即時失効（JWTモード対応）
--
-- 従来は「パスワード変更で古いセッションを即時失効できる」のはHMACモードだけ
-- （d1_sessions行の削除による）で、JWTモードでは既発行トークンが有効期限
-- （最長14日）まで残るという既知の制約があった。
--
-- 本カラムに「パスワードが変更された時刻（UNIX秒）」を記録することで、
-- JWTモードでも次の方針で即時失効を実現する:
--   - 管理者による再設定 / 設定画面での自己変更が UPDATE users ... password を
--     実行する際、同じUPDATE内で本カラムへ時刻を記録（追加クエリなし）
--   - ユーザー行をロードする書き込み系API（投稿・アカウント変更・管理操作等）は
--     トークン発行時刻(iat)と本カラムを突合し、iat が古いセッションを401で拒否する
--   - 閲覧系（公開データの取得）はステートレス検証のまま = JWTのD1読み取りゼロ
--     の利点は維持される
-- NULL（一度も変更されていないユーザー）は失効なしとして扱う。
-- 詳細はREADME「既知の制約」・src/middleware/auth.ts の assertSessionNotRevoked 参照。

ALTER TABLE users ADD COLUMN sessions_invalidated_at INTEGER;
